#!/usr/bin/env python3
"""Prepare a local binary download and complete, version-matched AI prompt."""
from pathlib import Path
import json
import re
import subprocess
import argparse

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--binary', type=Path, default=root / 'target/release/sigma')
parser.add_argument('--release-tag', help='Published release tag for download links')
args = parser.parse_args()
binary = args.binary.resolve()
if not binary.is_file():
    raise SystemExit('Build first: cargo build --locked --release')
# Keep public release addresses stable across local preview ports.
import tomllib
version = tomllib.loads((root / 'Cargo.toml').read_text())['package']['version']
tag = args.release_tag or 'v' + version
repository = 'https://github.com/omidz4t/sigma'
filename = 'sigma-linux-x86_64'
binary_url = f'{repository}/releases/download/{tag}/{filename}'
checksum_url = binary_url + '.sha256'
reference_url = f'https://raw.githubusercontent.com/omidz4t/sigma/{tag}/docs/REFERENCE.md'
help_text = subprocess.check_output([str(binary), '--help'], text=True)
commands = []
for line in help_text.split('COMMANDS:\n', 1)[1].splitlines():
    match = re.match(r'^  ([a-z][a-z-]*)\s', line)
    if match and match[1] not in commands:
        commands.append(match[1])
prompt = f'''Help me build a messaging bot or webxdc app using sigma, the stateful Rust CLI powered by chatmail core. Ask what I want to build before making changes or sending messages.

BINARY DOWNLOAD
Address: {{{{BINARY_URL}}}}
Platform: Linux / x86_64. This executable includes sigma and chatmail core; no Rust or Cargo installation is needed at runtime. System-library compatibility still applies. Hook executables and their runtimes are separate. Use this binary only on a compatible system; build from source for other platforms.
Checksum: {checksum_url}
Other platform downloads: {repository}/releases/tag/{tag}

Download and verify before running:
curl --fail --location '{{{{BINARY_URL}}}}' --output sigma
curl --fail --location '{checksum_url}' --output sigma.sha256
# The published checksum names the release asset; check the downloaded file:
expected=$(awk '{{print $1}}' sigma.sha256)
printf '%s  sigma\\n' "$expected" | sha256sum --check
chmod +x sigma
./sigma --help

The binary and checksum are published as GitHub Release assets, not committed to Git. Only run a downloaded binary after verification.

COMPLETE REFERENCE
{{{{REFERENCE_URL}}}}
Local repository alternative: docs/REFERENCE.md. Ask me to attach it if you cannot access either source.

OPERATING RULES
- Account data defaults to ~/.config/sigma; pass the same --data-path consistently for alternate accounts. Never commit credentials, private account data, or backups.
- Prefer --json. IDs are local to the account; contact IDs and chat IDs are different.
- Stop the listener/worker before commands needing direct access to the locked account.
- Chat slash commands: chat-hook-add CHAT_ID HOOK_ID EXECUTABLE --command /NAME, then listen. Input is JSON on stdin; stdout may be {{"reply":"text"}}.
- Webxdc: send once with --app NAME, reuse the name, register explicit hook types, then app-start. app-update is durable; app-events reads captured events. Realtime is ephemeral and joins only with a realtime-capable hook. Wait for realtime_joined before app-send.
- Do not publish, push, or contact people without my instructions.

ALL COMMANDS AND OPTIONS
The following help was generated from this same binary. Verify with ./sigma COMMAND --help when using a different version.

{help_text}
'''
for command in commands:
    prompt += '\n' + '=' * 60 + '\n'
    prompt += subprocess.check_output([str(binary), command, '--help'], text=True)
(root / 'landing/src/lib/prompt-data.js').write_text('// Generated by scripts/prepare-landing.py; contains public CLI help only.\nexport const SIGMA_AI_PROMPT = ' + json.dumps(prompt, ensure_ascii=False) + ';\nexport const SIGMA_BINARY_URL = ' + json.dumps(binary_url) + ';\nexport const SIGMA_REFERENCE_URL = ' + json.dumps(reference_url) + ';\n')
print(f'Prepared GitHub Release links for {tag} and complete help for {len(commands)} commands.')
